-- aplica o movimento no saldo do produto
create or replace function public.aplicar_movimento_estoque()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare delta numeric(14,3);
begin
  delta := case
    when new.tipo = 'entrada' then abs(new.quantidade)
    when new.tipo = 'saida' then -abs(new.quantidade)
    else new.quantidade
  end;

  update public.produtos
     set estoque_atual = coalesce(estoque_atual, 0) + delta,
         custo_medio = case
           when new.tipo = 'entrada' and new.custo_unitario is not null
             and coalesce(estoque_atual, 0) + delta > 0
           then ((coalesce(estoque_atual,0) * coalesce(custo_medio,0))
                 + (abs(new.quantidade) * new.custo_unitario))
                / (coalesce(estoque_atual,0) + delta)
           else custo_medio
         end
   where id = new.produto_id;

  return new;
end;
$$;

drop trigger if exists trg_aplicar_movimento_estoque on public.estoque_movimentos;
create trigger trg_aplicar_movimento_estoque
after insert on public.estoque_movimentos
for each row execute function public.aplicar_movimento_estoque();

