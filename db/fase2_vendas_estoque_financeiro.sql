  foreach t in array array['centros','fornecedores','pedidos','compras',
                           'contas_receber','contas_pagar','comissoes'] loop
    execute format('drop trigger if exists set_updated_at on public.%I', t);
    execute format('create trigger set_updated_at before update on public.%I for each row execute function public.set_updated_at()', t);
  end loop;
end $$;

-- ---------- POLICIES ----------
-- cadastros auxiliares: leitura autenticada, escrita gestor
do $$
declare t text;
begin
  foreach t in array array['centros','fornecedores'] loop
    execute format('drop policy if exists "%s_select_auth" on public.%I', t, t);
    execute format('create policy "%s_select_auth" on public.%I for select to authenticated using (true)', t, t);
    execute format('drop policy if exists "%s_write_manage" on public.%I', t, t);
    execute format('create policy "%s_write_manage" on public.%I for all to authenticated using (public.can_manage(auth.uid())) with check (public.can_manage(auth.uid()))', t, t);
  end loop;
end $$;

