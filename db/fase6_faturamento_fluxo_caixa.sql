create or replace function public.can_bill(_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.user_roles
    where user_id = _user_id and role in ('admin','gestor','financeiro')
  );
$$;

-- ---------- notas fiscais de saida ----------
create table if not exists public.notas_saida (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  pedido_id uuid not null references public.pedidos(id) on delete restrict,
  cliente_id uuid not null references public.clientes(id) on delete restrict,
  serie text not null default '1',
  nf_numero text,
  chave_acesso text,
  data_emissao date not null default current_date,
  valor_produtos numeric(14,2) not null default 0,
  valor_frete numeric(14,2) not null default 0,
  valor_desconto numeric(14,2) not null default 0,
  valor_total numeric(14,2) not null default 0,
  status text not null default 'emitida' check (status in ('emitida','cancelada')),
  observacoes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists notas_saida_pedido_idx on public.notas_saida(pedido_id);
create index if not exists notas_saida_cliente_idx on public.notas_saida(cliente_id);

grant select, insert, update, delete on public.notas_saida to authenticated;
grant all on public.notas_saida to service_role;
alter table public.notas_saida enable row level security;

drop policy if exists "notas_saida_select_auth" on public.notas_saida;
create policy "notas_saida_select_auth" on public.notas_saida
for select to authenticated using (true);

drop policy if exists "notas_saida_write_bill" on public.notas_saida;
create policy "notas_saida_write_bill" on public.notas_saida
for all to authenticated
using (public.can_bill(auth.uid()))
with check (public.can_bill(auth.uid()));

drop trigger if exists trg_notas_saida_updated on public.notas_saida;
create trigger trg_notas_saida_updated
before update on public.notas_saida
for each row execute function public.set_updated_at();

-- ---------- faturar pedido ----------
create or replace function public.faturar_pedido(_pedido_id uuid, _nf_numero text default null, _serie text default '1')
returns public.notas_saida
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  ped record;
  nota public.notas_saida;
begin
  if not public.can_bill(auth.uid()) then
    raise exception 'Sem permissao para faturar pedidos';
  end if;

  select * into ped from public.pedidos where id = _pedido_id;
  if ped is null then raise exception 'Pedido nao encontrado'; end if;
  if ped.status <> 'confirmado' then
    raise exception 'Somente pedidos confirmados podem ser faturados';
  end if;
  if exists (select 1 from public.notas_saida
              where pedido_id = _pedido_id and status = 'emitida') then
    raise exception 'Pedido ja possui nota fiscal emitida';
  end if;

  insert into public.notas_saida
    (pedido_id, cliente_id, serie, nf_numero, valor_produtos, valor_frete,
     valor_desconto, valor_total, created_by)
  values (ped.id, ped.cliente_id, coalesce(nullif(_serie,''), '1'), nullif(_nf_numero,''),
          ped.total_itens, ped.frete_valor, ped.desconto_valor, ped.total_liquido, auth.uid())
  returning * into nota;

  update public.pedidos set status = 'faturado' where id = _pedido_id;

  insert into public.auditoria (tabela, registro_id, acao, detalhe, user_id)
  values ('notas_saida', nota.id, 'faturar',
          jsonb_build_object('pedido', ped.numero, 'total', nota.valor_total), auth.uid());

  perform public.notificar('Pedido faturado',
    'Pedido ' || ped.numero || ' faturado por ' || to_char(nota.valor_total, 'FM999999990.00'),
    'sucesso', '/faturamento');

  return nota;
end;
$$;

grant execute on function public.faturar_pedido(uuid, text, text) to authenticated;

create or replace function public.cancelar_nota_saida(_id uuid)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  nota record;
begin
  if not public.can_bill(auth.uid()) then
    raise exception 'Sem permissao para cancelar notas';
  end if;

  select * into nota from public.notas_saida where id = _id;
  if nota is null then raise exception 'Nota nao encontrada'; end if;

  update public.notas_saida set status = 'cancelada' where id = _id;
  update public.pedidos set status = 'confirmado' where id = nota.pedido_id;

  insert into public.auditoria (tabela, registro_id, acao, detalhe, user_id)
  values ('notas_saida', _id, 'cancelar', jsonb_build_object('total', nota.valor_total), auth.uid());
end;
$$;

grant execute on function public.cancelar_nota_saida(uuid) to authenticated;

-- ---------- fluxo de caixa consolidado ----------
create or replace view public.vw_fluxo_caixa as
select
  to_char(vencimento, 'YYYY-MM') as periodo,
  sum(case when status <> 'cancelado' then valor - valor_pago else 0 end) as previsto_entrada,
  sum(valor_pago) as realizado_entrada,
  0::numeric as previsto_saida,
  0::numeric as realizado_saida
from public.contas_receber
group by 1
union all
select
  to_char(vencimento, 'YYYY-MM') as periodo,
  0::numeric,
  0::numeric,
  sum(case when status <> 'cancelado' then valor - valor_pago else 0 end),
  sum(valor_pago)
from public.contas_pagar
group by 1;

grant select on public.vw_fluxo_caixa to authenticated;

