create or replace function public.can_ship(_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.user_roles
    where user_id = _user_id and role in ('admin','gestor','expedicao','estoque')
  );
$$;

-- ---------- transportadoras ----------
create table if not exists public.transportadoras (
  id uuid primary key default gen_random_uuid(),
  codigo text unique,
  razao_social text not null,
  cnpj text,
  email text,
  telefone text,
  cidade text,
  uf text,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

grant select, insert, update, delete on public.transportadoras to authenticated;
grant all on public.transportadoras to service_role;
alter table public.transportadoras enable row level security;

drop policy if exists "transportadoras_select_auth" on public.transportadoras;
create policy "transportadoras_select_auth" on public.transportadoras
for select to authenticated using (true);

drop policy if exists "transportadoras_write_manage" on public.transportadoras;
create policy "transportadoras_write_manage" on public.transportadoras
for all to authenticated
using (public.can_manage(auth.uid()))
with check (public.can_manage(auth.uid()));

drop trigger if exists set_updated_at_transportadoras on public.transportadoras;
create trigger set_updated_at_transportadoras before update on public.transportadoras
for each row execute function public.set_updated_at();

-- ---------- expedicoes (romaneio de entrega) ----------
create table if not exists public.expedicoes (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  pedido_id uuid not null references public.pedidos(id) on delete cascade,
  centro_id uuid references public.centros(id) on delete set null,
  transportadora_id uuid references public.transportadoras(id) on delete set null,
  motorista text,
  placa text,
  status text not null default 'pendente'
    check (status in ('pendente','separacao','em_rota','entregue','cancelada')),
  previsao_entrega date,
  data_saida date,
  data_entrega date,
  peso_kg numeric(14,3) not null default 0,
  volumes int not null default 1,
  observacoes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists expedicoes_pedido_idx on public.expedicoes(pedido_id);
create index if not exists expedicoes_status_idx on public.expedicoes(status);

grant select, insert, update, delete on public.expedicoes to authenticated;
grant all on public.expedicoes to service_role;
alter table public.expedicoes enable row level security;

drop policy if exists "expedicoes_select_auth" on public.expedicoes;
create policy "expedicoes_select_auth" on public.expedicoes
for select to authenticated using (true);

drop policy if exists "expedicoes_write_ship" on public.expedicoes;
create policy "expedicoes_write_ship" on public.expedicoes
for all to authenticated
using (public.can_ship(auth.uid()))
with check (public.can_ship(auth.uid()));

drop trigger if exists set_updated_at_expedicoes on public.expedicoes;
create trigger set_updated_at_expedicoes before update on public.expedicoes
for each row execute function public.set_updated_at();

-- ---------- notificacoes ----------
create table if not exists public.notificacoes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade, -- null = todos
  titulo text not null,
  mensagem text,
  tipo text not null default 'info' check (tipo in ('info','alerta','erro','sucesso')),
  link text,
  lida boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists notificacoes_user_idx on public.notificacoes(user_id, lida);

grant select, insert, update, delete on public.notificacoes to authenticated;
grant all on public.notificacoes to service_role;
alter table public.notificacoes enable row level security;

drop policy if exists "notificacoes_select_own" on public.notificacoes;
create policy "notificacoes_select_own" on public.notificacoes
for select to authenticated using (user_id is null or user_id = auth.uid());

drop policy if exists "notificacoes_update_own" on public.notificacoes;
create policy "notificacoes_update_own" on public.notificacoes
for update to authenticated
using (user_id is null or user_id = auth.uid())
with check (user_id is null or user_id = auth.uid());

drop policy if exists "notificacoes_insert_auth" on public.notificacoes;
create policy "notificacoes_insert_auth" on public.notificacoes
for insert to authenticated with check (true);

drop policy if exists "notificacoes_delete_manage" on public.notificacoes;
create policy "notificacoes_delete_manage" on public.notificacoes
for delete to authenticated using (public.can_manage(auth.uid()));

create or replace function public.notificar(_titulo text, _mensagem text, _tipo text default 'info', _link text default null)
returns void
language sql
security definer
set search_path = public
as $$
  insert into public.notificacoes (titulo, mensagem, tipo, link)
  values (_titulo, _mensagem, coalesce(_tipo, 'info'), _link);
$$;

-- pedido confirmado -> gera expedicao pendente + notificacao
create or replace function public.pedidos_after_confirm()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'confirmado' and coalesce(old.status, '') <> 'confirmado' then
    insert into public.expedicoes (pedido_id, centro_id, status, created_by)
    select new.id, new.centro_id, 'pendente', new.created_by
    where not exists (
      select 1 from public.expedicoes e
      where e.pedido_id = new.id and e.status <> 'cancelada'
    );

    perform public.notificar(
      'Pedido ' || new.numero || ' confirmado',
      'Expedicao gerada para separacao.',
      'sucesso',
      '/expedicao'
    );
  end if;
  return new;
end;
$$;

drop trigger if exists pedidos_after_confirm on public.pedidos;
create trigger pedidos_after_confirm after update on public.pedidos
for each row execute function public.pedidos_after_confirm();

-- estoque abaixo do minimo -> notificacao de alerta
create or replace function public.produtos_alerta_estoque()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if coalesce(new.estoque_minimo, 0) > 0
     and new.estoque_atual <= new.estoque_minimo
     and coalesce(old.estoque_atual, 0) > coalesce(old.estoque_minimo, 0) then
    perform public.notificar(
      'Estoque minimo: ' || new.descricao,
      'Saldo atual ' || new.estoque_atual || ' (minimo ' || new.estoque_minimo || ').',
      'alerta',
      '/estoque'
    );
  end if;
  return new;
end;
$$;

drop trigger if exists produtos_alerta_estoque on public.produtos;
create trigger produtos_alerta_estoque after update of estoque_atual on public.produtos
for each row execute function public.produtos_alerta_estoque();

-- ---------- fluxo de expedicao ----------
create or replace function public.avancar_expedicao(_id uuid, _status text, _data date default current_date)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_exp public.expedicoes;
begin
  if not public.can_ship(auth.uid()) then
    raise exception 'Sem permissao para movimentar expedicoes';
  end if;

  select * into v_exp from public.expedicoes where id = _id for update;
  if v_exp.id is null then
    raise exception 'Expedicao nao encontrada';
  end if;
  if v_exp.status in ('entregue','cancelada') then
    raise exception 'Expedicao ja finalizada';
  end if;
  if _status not in ('separacao','em_rota','entregue','cancelada') then
    raise exception 'Status invalido';
  end if;

  update public.expedicoes
  set status = _status,
      data_saida = case when _status = 'em_rota' then coalesce(_data, current_date) else data_saida end,
      data_entrega = case when _status = 'entregue' then coalesce(_data, current_date) else data_entrega end
  where id = _id;

  insert into public.auditoria (usuario_id, acao, entidade, entidade_id, detalhe)
  values (auth.uid(), 'expedicao_' || _status, 'expedicoes', _id,
          jsonb_build_object('status_anterior', v_exp.status, 'status', _status));

  perform public.notificar(
    'Expedicao ' || v_exp.numero || ' -> ' || _status,
    'Atualizada em ' || coalesce(_data, current_date)::text,
    case when _status = 'cancelada' then 'alerta' else 'info' end,
    '/expedicao'
  );
end;
$$;

-- ---------- relatorios (views) ----------
create or replace view public.vw_vendas_mensal
with (security_invoker = on) as
select
  to_char(date_trunc('month', p.data_pedido), 'YYYY-MM') as mes,
  count(*)::int as pedidos,
  sum(p.total_liquido) as total,
  sum(p.comissao_valor) as comissao
from public.pedidos p
where p.status in ('confirmado', 'faturado')
group by 1
order by 1 desc;

create or replace view public.vw_top_produtos
with (security_invoker = on) as
select
  pr.id as produto_id,
  pr.descricao,
  sum(pi.quantidade) as quantidade,
  sum(pi.total) as total
from public.pedido_itens pi
join public.pedidos p on p.id = pi.pedido_id
join public.produtos pr on pr.id = pi.produto_id
where p.status in ('confirmado', 'faturado')
group by 1, 2
order by total desc;

create or replace view public.vw_top_clientes
with (security_invoker = on) as
select
  c.id as cliente_id,
  c.razao_social,
  count(p.id)::int as pedidos,
  sum(p.total_liquido) as total
from public.pedidos p
join public.clientes c on c.id = p.cliente_id
where p.status in ('confirmado', 'faturado')
group by 1, 2
order by total desc;

create or replace view public.vw_comissoes_representante
with (security_invoker = on) as
select
  r.id as representante_id,
  r.nome,
  sum(case when cm.status = 'paga' then cm.valor else 0 end) as pago,
  sum(case when cm.status in ('prevista','liberada') then cm.valor else 0 end) as a_pagar
from public.comissoes cm
join public.representantes r on r.id = cm.representante_id
group by 1, 2
order by a_pagar desc;

grant select on public.vw_vendas_mensal to authenticated;
grant select on public.vw_top_produtos to authenticated;
grant select on public.vw_top_clientes to authenticated;
grant select on public.vw_comissoes_representante to authenticated;

