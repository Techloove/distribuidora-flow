-- preco vigente do produto para um cliente (fallback: produtos.preco_venda)
create or replace function public.preco_produto(_produto_id uuid, _cliente_id uuid default null)
returns numeric
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  cli record;
  achado numeric;
begin
  select * into cli from public.clientes where id = _cliente_id;

  select i.preco into achado
  from public.tabela_preco_itens i
  join public.tabelas_preco t on t.id = i.tabela_id
  where i.produto_id = _produto_id
    and t.ativo
    and t.vigencia_inicio <= current_date
    and (t.vigencia_fim is null or t.vigencia_fim >= current_date)
    and (t.cliente_id is null or t.cliente_id = _cliente_id)
    and (t.uf is null or t.uf = coalesce(cli.uf, t.uf))
  order by (t.cliente_id is not null) desc, (t.uf is not null) desc, t.prioridade desc
  limit 1;

  if achado is null then
    select preco_venda into achado from public.produtos where id = _produto_id;
  end if;

  return coalesce(achado, 0);
end;
$$;

grant execute on function public.preco_produto(uuid, uuid) to authenticated;

