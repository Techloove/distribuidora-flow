-- total do item e da devolucao
create or replace function public.devolucao_itens_calc()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.total := round(new.quantidade * new.preco_unitario, 2);
  return new;
end;
$$;

drop trigger if exists trg_devolucao_itens_calc on public.devolucao_itens;
create trigger trg_devolucao_itens_calc
before insert or update on public.devolucao_itens
for each row execute function public.devolucao_itens_calc();

create or replace function public.recalcular_devolucao()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  alvo uuid := coalesce(new.devolucao_id, old.devolucao_id);
begin
  update public.devolucoes d
  set valor_total = coalesce((select sum(total) from public.devolucao_itens where devolucao_id = alvo), 0)
  where d.id = alvo;
  return null;
end;
$$;

drop trigger if exists trg_recalcular_devolucao on public.devolucao_itens;
create trigger trg_recalcular_devolucao
after insert or update or delete on public.devolucao_itens
for each row execute function public.recalcular_devolucao();

-- confirma devolucao: volta estoque + gera credito no contas a receber
create or replace function public.confirmar_devolucao(_id uuid)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  dev record;
  it record;
begin
  if not public.can_manage(auth.uid()) then
    raise exception 'Sem permissao para confirmar devolucoes';
  end if;

  select * into dev from public.devolucoes where id = _id;
  if dev is null then raise exception 'Devolucao nao encontrada'; end if;
  if dev.status <> 'rascunho' then
    raise exception 'Somente devolucoes em rascunho podem ser confirmadas';
  end if;
  if not exists (select 1 from public.devolucao_itens where devolucao_id = _id) then
    raise exception 'Inclua ao menos um item na devolucao';
  end if;

  for it in select * from public.devolucao_itens where devolucao_id = _id loop
    insert into public.estoque_movimentos
      (produto_id, centro_id, tipo, quantidade, custo_unitario, origem, documento_id, observacao, created_by)
    values (it.produto_id, dev.centro_id, 'entrada', it.quantidade, it.preco_unitario,
            'devolucao', dev.id, 'Devolucao ' || dev.numero, auth.uid());
  end loop;

  insert into public.contas_receber
    (cliente_id, pedido_id, documento, parcela, valor, vencimento, status, observacao)
  values (dev.cliente_id, dev.pedido_id, 'DEV-' || dev.numero, 1,
          -1 * dev.valor_total, current_date, 'aberto',
          'Credito de devolucao ' || dev.numero);

  update public.devolucoes set status = 'confirmada' where id = _id;

  insert into public.auditoria (tabela, registro_id, acao, detalhe, user_id)
  values ('devolucoes', _id, 'confirmar',
          jsonb_build_object('numero', dev.numero, 'valor', dev.valor_total), auth.uid());

  perform public.notificar('Devolucao confirmada',
    'Devolucao ' || dev.numero || ' retornou ao estoque e gerou credito ao cliente.',
    'alerta', '/devolucoes');
end;
$$;

grant execute on function public.confirmar_devolucao(uuid) to authenticated;

create or replace function public.cancelar_devolucao(_id uuid)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  dev record;
  it record;
begin
  if not public.can_manage(auth.uid()) then
    raise exception 'Sem permissao para cancelar devolucoes';
  end if;

  select * into dev from public.devolucoes where id = _id;
  if dev is null then raise exception 'Devolucao nao encontrada'; end if;

  if dev.status = 'confirmada' then
    for it in select * from public.devolucao_itens where devolucao_id = _id loop
      insert into public.estoque_movimentos
        (produto_id, centro_id, tipo, quantidade, custo_unitario, origem, documento_id, observacao, created_by)
      values (it.produto_id, dev.centro_id, 'saida', it.quantidade, it.preco_unitario,
              'devolucao_cancelada', dev.id, 'Cancelamento devolucao ' || dev.numero, auth.uid());
    end loop;

    update public.contas_receber
      set status = 'cancelado'
      where documento = 'DEV-' || dev.numero;
  end if;

  update public.devolucoes set status = 'cancelada' where id = _id;

  insert into public.auditoria (tabela, registro_id, acao, detalhe, user_id)
  values ('devolucoes', _id, 'cancelar', jsonb_build_object('numero', dev.numero), auth.uid());
end;
$$;

grant execute on function public.cancelar_devolucao(uuid) to authenticated;

