create or replace view public.vw_metas_acompanhamento as
select
  m.id,
  m.representante_id,
  r.nome as representante,
  m.ano,
  m.mes,
  m.valor_meta,
  coalesce(v.realizado, 0) as realizado,
  case when m.valor_meta > 0
       then round(coalesce(v.realizado, 0) / m.valor_meta * 100, 2)
       else 0 end as atingimento_percentual
from public.metas_vendas m
left join public.representantes r on r.id = m.representante_id
left join (
  select representante_id,
         extract(year from data_pedido)::int as ano,
         extract(month from data_pedido)::int as mes,
         sum(total_liquido) as realizado
  from public.pedidos
  where status in ('confirmado','faturado')
  group by 1, 2, 3
) v on v.representante_id = m.representante_id and v.ano = m.ano and v.mes = m.mes;

grant select on public.vw_metas_acompanhamento to authenticated;

