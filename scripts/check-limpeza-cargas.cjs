const { PGlite } = require("@electric-sql/pglite"),
  fs = require("node:fs"),
  path = require("node:path"),
  assert = require("node:assert/strict");
(async () => {
  const d = new PGlite();
  try {
    await d.exec(`create schema auth;create function auth.uid() returns uuid language sql as $$select null::uuid$$;
 create table cargas(id int primary key,numero bigint generated by default as identity unique,status text);
 create table pedidos(id int primary key,status text);
 create table carga_pedidos(carga_id int references cargas(id) on delete cascade,pedido_id int references pedidos(id));
 create table expedicoes(id int,pedido_id int,status text,carga_id int references cargas(id) on delete set null);
 create table entrega_registros(id serial primary key,pedido_id int,tipo text);create table entrega_itens(registro_id int);create table notas_saida(pedido_id int,status text);
 create table auditoria(tabela text,acao text,user_id uuid,detalhe jsonb);
 create table contas_receber(pedido_id int,valor numeric);create table estoque_movimentos(pedido_id int,quantidade numeric);
 insert into cargas(id,status) values(1,'aberta'),(2,'em_rota'),(3,'concluida');
 insert into pedidos values(1,'em_carga'),(2,'em_rota'),(3,'entregue'),(4,'em_carga'),(5,'conferido');
 insert into carga_pedidos values(1,1),(2,2),(3,3),(1,4);
 insert into expedicoes values(1,1,'aguardando_entrega',1),(2,2,'em_rota',2),(3,3,'entregue',3),(4,4,'aguardando_entrega',1);
 insert into entrega_registros(pedido_id,tipo) values(3,'entrega');insert into notas_saida values(4,'autorizada');
 insert into contas_receber values(1,100);insert into estoque_movimentos values(1,10);`);
    const sql = fs.readFileSync(
      path.join(__dirname, "../db/limpar_cargas_reiniciar_numero1.sql"),
      "utf8",
    );
    const q = async (s) => (await d.query(s)).rows;
    // Unknown foreign keys block the entire operation, even when DELETE CASCADE would succeed.
    await d.exec("create table outra_rotina(carga_id int references cargas(id) on delete cascade)");
    await assert.rejects(d.exec(sql), /outra tabela/);
    await d.exec("rollback");
    assert.equal((await q("select count(*) n from cargas"))[0].n, 3);
    await d.exec("drop table outra_rotina");
    // Inconsistent in-load order with receipt/route evidence cannot be silently rewound.
    await d.exec("insert into entrega_registros(pedido_id,tipo) values(1,'entrega')");
    await assert.rejects(d.exec(sql), /evidência/);
    await d.exec("rollback");
    await d.exec("delete from entrega_registros where pedido_id=1");
    await d.exec(sql);
    assert.equal((await q("select count(*) n from cargas"))[0].n, 0);
    assert.equal((await q("select count(*) n from carga_pedidos"))[0].n, 0);
    assert.deepEqual(
      (await q("select status from pedidos order by id")).map((r) => r.status),
      ["faturado", "em_rota", "entregue", "nf_emitida", "conferido"],
    );
    assert.equal((await q("select count(*) n from expedicoes where carga_id is not null"))[0].n, 0);
    assert.equal((await q("select count(*) n from expedicoes"))[0].n, 4);
    assert.equal((await q("select count(*) n from entrega_registros"))[0].n, 1);
    assert.equal(Number((await q("select sum(valor) v from contas_receber"))[0].v), 100);
    assert.equal(Number((await q("select sum(quantidade) v from estoque_movimentos"))[0].v), 10);
    const snapshot = (await q("select detalhe from auditoria"))[0].detalhe;
    assert.equal(snapshot.cargas.length, 3);
    assert.equal(snapshot.vinculos.length, 4);
    await d.exec(sql);
    assert.equal((await q("select count(*) n from auditoria"))[0].n, 1);
    assert.equal(
      Number(
        (await q("insert into cargas(id,status) values(4,'aberta') returning numero"))[0].numero,
      ),
      1,
    );
    // Sequence restart rolls back together with the deletion if the transaction is not committed.
    const uncommitted = sql.replace(/commit;\s*$/i, "rollback;");
    await d.exec(uncommitted);
    assert.equal((await q("select count(*) n from cargas"))[0].n, 1);
    assert.equal(
      Number(
        (await q("insert into cargas(id,status) values(5,'aberta') returning numero"))[0].numero,
      ),
      2,
    );
    console.log(
      "OK limpeza cargas: cópia na auditoria, liberação só antes da saída, entregas/financeiro/estoque preservados, dependências e inconsistências bloqueadas, repetição sem duplicar auditoria, próximo número1 e rollback transacional da sequência.",
    );
  } finally {
    await d.close();
  }
})().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
